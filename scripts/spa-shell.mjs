// build:tauri post-step — shape the static bundle for the Tauri shell and LAN
// clients:
//
// 1. The SPA shell is emitted as `_shell.html`; copy it to `index.html`.
// 2. The platform PWA injector bakes og:/twitter:/apple-mobile-web-app meta
//    and the Grok chrome script into the prerendered head. The client render
//    (src/routes/__root.tsx) does not produce those nodes, so hydration
//    mismatches (React #418) on every boot of the embedded shell. The web
//    deploy keeps the injector (its middleware re-adds everything per
//    response); only the embedded copy is cleaned.
// 3. Add a static manifest — the deployed one is generated by server
//    middleware that does not exist in the static bundle.
import { copyFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const staticDir = join(root, ".vercel/output/static");

let html = await (await import("node:fs/promises")).readFile(
  join(staticDir, "_shell.html"),
  "utf8",
);

const stripped = [
  // og:/twitter: cards and app-capable chrome — injected per-response on the
  // web deploy, never rendered by the client tree.
  /<meta name="twitter:card"[^>]*>\s*/g,
  /<meta property="og:[^"]*"[^>]*>\s*/g,
  /<meta name="apple-mobile-web-app-[^>]*>\s*/g,
  // Grok page chrome script — the desktop shell has no Grok page driving it.
  /<script src="https:\/\/grok\.com\/grok-app-builder\/extensions\.js"[^>]*><\/script>\s*/g,
];
for (const pattern of stripped) html = html.replace(pattern, "");

await writeFile(join(staticDir, "index.html"), html);

await writeFile(
  join(staticDir, "__grok/manifest.webmanifest"),
  JSON.stringify(
    {
      name: "COMO Desk",
      short_name: "COMO",
      start_url: "/",
      display: "standalone",
      background_color: "#f3ecdf",
      theme_color: "#f3ecdf",
      icons: [
        { src: "/__grok/icon-180.png", sizes: "180x180", type: "image/png" },
      ],
    },
    null,
    2,
  ),
);

console.log("[spa-shell] index.html + manifest ready");
